// Helper function to get all tasks
export const getAllTasks = () => {
  return [
    ...landsraadTasks.craftedItems.map(task => ({ ...task, type: 'crafted' })),
    ...landsraadTasks.rawMaterials.map(task => ({ ...task, type: 'raw' })),
    ...landsraadTasks.killTasks.map(task => ({ ...task, type: 'kill' })),
    ...landsraadTasks.vehicleTasks.map(task => ({ ...task, type: 'vehicle' }))
  ];
};

// Helper function to get tasks by type
export const getTasksByType = (type) => {
  switch (type) {
    case 'crafted':
      return landsraadTasks.craftedItems;
    case 'raw':
      return landsraadTasks.rawMaterials;
    case 'kill':
      return landsraadTasks.killTasks;
    case 'vehicle':
      return landsraadTasks.vehicleTasks;
    default:
      return getAllTasks();
  }
};

// Helper function to search tasks
export const searchTasks = (query) => {
  const allTasks = getAllTasks();
  return allTasks.filter(task => 
    task.name.toLowerCase().includes(query.toLowerCase())
  );
};

